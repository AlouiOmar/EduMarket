import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import { authRoutes } from './modules/auth/routes.js';
import { courseRoutes } from './modules/courses/routes.js';
import { courseAssetRoutes } from './modules/courses/assets.routes.js';
import { courseStructureRoutes } from './modules/courses/structure.routes.js';
import { enrollmentRoutes } from './modules/enrollments/routes.js';
import { teacherVerificationRoutes } from './modules/teacher-verification/routes.js';
import { teacherApplicationRoutes } from './modules/teacher-applications/routes.js';
import { adminUserRoutes } from './modules/admin/users.routes.js';
import { adminSettingsRoutes, isMaintenanceEnabled, platformPublicRoutes, platformStatusRoutes } from './modules/admin/settings.routes.js';
import { sessionRoutes } from './modules/sessions/routes.js';
import { certificateRoutes } from './modules/certificates/routes.js';
import { notificationRoutes } from './modules/notifications/routes.js';
import { examRoutes } from './modules/exams/routes.js';
import { messagingRoutes } from './modules/messaging/routes.js';
import { forumRoutes } from './modules/forum/routes.js';
import { assignmentRoutes } from './modules/assignments/routes.js';
import { paymentRoutes, paymentWebhookRoutes } from './modules/payments/routes.js';
import { adminPaymentRoutes } from './modules/admin/payments.routes.js';
import { adminAuditRoutes } from './modules/admin/audit.routes.js';
import { adminCatalogRoutes } from './modules/admin/catalog.routes.js';
import { classRoutes } from './modules/classes/routes.js';
import { storageRoutes } from './modules/storage/routes.js';
import { adminOfflinePaymentRoutes, offlinePaymentRoutes } from './modules/payments/offline.routes.js';
import { moderationRoutes } from './modules/moderation/routes.js';
import { supportRoutes, adminSupportRoutes } from './modules/support/routes.js';
import { analyticsRoutes } from './modules/analytics/routes.js';
import { adminCategoryRoutes } from './modules/categories/routes.js';
import { calendarRoutes } from './modules/calendar/routes.js';
import { subscriptionRoutes } from './modules/subscriptions/routes.js';
import { adminLearningPathRoutes, learningPathRoutes } from './modules/learning-paths/routes.js';
import { reportModerationRoutes, reportRoutes } from './modules/reports/routes.js';
import { institutionRoutes } from './modules/institutions/routes.js';
import { institutionVerificationRoutes } from './modules/institutions/verification.routes.js';
import { courseReviewRoutes } from './modules/courses/review.routes.js';
import { lessonQuestionRoutes } from './modules/courses/questions.routes.js';
import { favoriteRoutes } from './modules/courses/favorites.routes.js';
import { publicTeacherRoutes } from './modules/teachers/public.routes.js';
import { gradebookRoutes } from './modules/gradebook/routes.js';
import { assessmentRoutes } from './modules/assessments/routes.js';
import { participationRoutes } from './modules/participation/routes.js';
import { courseAnalyticsRoutes } from './modules/analytics/course.routes.js';
import { courseTemplateRoutes } from './modules/courses/templates.routes.js';
import { aiRoutes } from './modules/ai/routes.js';
import { ltiRoutes } from './modules/lti/routes.js';
import { scormContentRoutes, scormRoutes } from './modules/scorm/routes.js';
import { courseFileRoutes } from './modules/courses/files.routes.js';
import { errorHandler } from './common/errors.js';

export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.CORS_ORIGIN, credentials: true, methods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE'], allowedHeaders: ['Content-Type', 'Authorization', 'Idempotency-Key'] }));
app.use('/api/v1', rateLimit({ windowMs: 60_000, limit: env.NODE_ENV === 'test' ? 1000 : 120, standardHeaders: true, legacyHeaders: false }));
// Provider webhooks need the exact raw body for signature verification and must work during maintenance.
app.use('/api/v1/payments/webhooks', paymentWebhookRoutes);
// Lesson blocks (rich text, HTML, code) and course packages need larger bodies; every other route keeps the small limit.
const contentJson = express.json({ limit: '2mb' }), defaultJson = express.json({ limit: '32kb' });
// Assessment content (question prompts, test instructions) can also exceed the default limit.
app.use((req, res, next) => (/^\/(api\/v1\/(courses\/[a-f\d]{24}\/structure\/|assessments\/|participation\/)|scorm-content\/)/i.test(req.path) ? contentJson : defaultJson)(req, res, next));
// Imported SCORM content: served only on SCORM_CONTENT_ORIGIN (host-checked), outside /api/v1 and its session cookie path.
app.use('/scorm-content', scormContentRoutes);
app.get('/api/v1/health', (_req, res) => res.json({ success: true, data: { status: 'ok' } }));
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/platform/status', platformStatusRoutes);
app.use('/api/v1/platform', platformPublicRoutes);
app.use('/api/v1', async (req, res, next) => {
  if (req.path.startsWith('/admin/')) return next();
  try {
    if (await isMaintenanceEnabled()) return res.status(503).json({ success: false, error: { code: 'MAINTENANCE_MODE' } });
    next();
  } catch (error) { next(error); }
});
app.use('/api/v1/courses', courseRoutes);
app.use('/api/v1/courses', courseAssetRoutes);
app.use('/api/v1/courses', courseReviewRoutes);
app.use('/api/v1/courses', lessonQuestionRoutes);
app.use('/api/v1/courses', courseStructureRoutes);
app.use('/api/v1/courses', courseTemplateRoutes);
app.use('/api/v1/courses', courseFileRoutes);
app.use('/api/v1/favorites', favoriteRoutes);
app.use('/api/v1/teachers', publicTeacherRoutes);
app.use('/api/v1/enrollments', enrollmentRoutes);
app.use('/api/v1/teacher-verifications', teacherVerificationRoutes);
app.use('/api/v1/teacher-applications', teacherApplicationRoutes);
app.use('/api/v1/admin/users', adminUserRoutes);
app.use('/api/v1/admin/settings', adminSettingsRoutes);
app.use('/api/v1/admin/payments', adminPaymentRoutes);
app.use('/api/v1/admin/payments', adminOfflinePaymentRoutes);
app.use('/api/v1/admin/audit-logs', adminAuditRoutes);
app.use('/api/v1/admin/support', adminSupportRoutes);
app.use('/api/v1/admin/categories', adminCategoryRoutes);
app.use('/api/v1/moderation/reports', reportModerationRoutes);
app.use('/api/v1/moderation', moderationRoutes);
app.use('/api/v1/reports', reportRoutes);
app.use('/api/v1/support', supportRoutes);
app.use('/api/v1/analytics', courseAnalyticsRoutes);
app.use('/api/v1/analytics', analyticsRoutes);
app.use('/api/v1/calendar', calendarRoutes);
app.use('/api/v1/subscriptions', subscriptionRoutes);
app.use('/api/v1/classes', classRoutes);
app.use('/api/v1/storage', storageRoutes);
app.use('/api/v1/learning-paths', learningPathRoutes);
app.use('/api/v1/admin/learning-paths', adminLearningPathRoutes);
app.use('/api/v1/admin', adminCatalogRoutes);
app.use('/api/v1/sessions', sessionRoutes);
app.use('/api/v1/certificates', certificateRoutes);
app.use('/api/v1/notifications', notificationRoutes);
app.use('/api/v1/exams', examRoutes);
app.use('/api/v1/messaging', messagingRoutes);
app.use('/api/v1/forum', forumRoutes);
app.use('/api/v1/assignments', assignmentRoutes);
app.use('/api/v1/gradebook', gradebookRoutes);
app.use('/api/v1/assessments', assessmentRoutes);
app.use('/api/v1/participation', participationRoutes);
app.use('/api/v1/ai', aiRoutes);
app.use('/api/v1/lti', ltiRoutes);
app.use('/api/v1/scorm', scormRoutes);
app.use('/api/v1/payments', paymentRoutes);
app.use('/api/v1/payments', offlinePaymentRoutes);
app.use('/api/v1/institutions', institutionRoutes);
app.use('/api/v1/institution-verifications', institutionVerificationRoutes);
app.use((_req, res) => res.status(404).json({ success: false, error: { code: 'NOT_FOUND' } }));
app.use(errorHandler);
